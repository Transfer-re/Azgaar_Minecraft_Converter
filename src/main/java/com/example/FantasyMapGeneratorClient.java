package com.example;

import java.nio.file.Path;

import net.minecraft.resource.ResourcePackProfile;
import net.minecraft.resource.ResourcePackSource;
import net.minecraft.resource.ResourceType;
import net.minecraft.text.Text;
import net.minecraftforge.event.AddPackFindersEvent;
import net.minecraftforge.eventbus.api.IEventBus;
import net.minecraftforge.fml.ModList;
import net.minecraftforge.resource.PathPackResources;

import com.example.border.ClientBorderOverlay;

/** Client-side setup; {@link FantasyMapGenerator} calls it on the client only. */
public final class FantasyMapGeneratorClient {
	private FantasyMapGeneratorClient() {
	}

	public static void init(IEventBus modBus) {
		ClientBorderOverlay.registerClient();
		modBus.addListener(FantasyMapGeneratorClient::registerConquestSky);
	}

	/**
	 * Conquest Reforged's Polytone sky and fog colormaps target the vanilla
	 * overworld dimension type, which FMG worlds don't use (they have their own
	 * height tiers). This pack, generated by tools/fmgtrees/make_datapack.py,
	 * points FMG's dimension types at the same textures.
	 */
	private static void registerConquestSky(AddPackFindersEvent event) {
		if (event.getPackType() != ResourceType.CLIENT_RESOURCES || !ModList.get().isLoaded("conquest")) return;
		Path root = ModList.get().getModFileById(FantasyMapGenerator.MOD_ID).getFile()
				.findResource("resourcepacks", "conquest_sky");
		// always enabled, like Fabric's ResourcePackActivationType.ALWAYS_ENABLED
		ResourcePackProfile pack = ResourcePackProfile.create(
				FantasyMapGenerator.MOD_ID + ":conquest_sky", Text.literal("Fantasy Map: Conquest sky"), true,
				name -> new PathPackResources(name, true, root), ResourceType.CLIENT_RESOURCES,
				ResourcePackProfile.InsertionPosition.TOP, ResourcePackSource.BUILTIN);
		if (pack != null) {
			event.addRepositorySource(adder -> adder.accept(pack));
		}
	}
}
