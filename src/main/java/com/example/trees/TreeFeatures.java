package com.example.trees;

import static net.minecraft.server.command.CommandManager.literal;

import java.util.ArrayList;
import java.util.IdentityHashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.atomic.LongAdder;

import com.example.FantasyMapGenerator;
import com.example.surface.SurfaceSet;
import com.example.worldgen.ImageMapChunkGenerator;
import com.example.worldmap.runtime.MapImageCache;

import net.neoforged.fml.loading.FMLPaths;
import net.neoforged.neoforge.common.NeoForge;
import net.neoforged.neoforge.event.OnDatapackSyncEvent;
import net.neoforged.neoforge.event.RegisterCommandsEvent;
import net.neoforged.neoforge.event.server.ServerStoppedEvent;
import net.neoforged.neoforge.registries.RegisterEvent;
import net.minecraft.registry.RegistryKey;
import net.minecraft.registry.RegistryKeys;
import net.minecraft.server.command.ServerCommandSource;
import net.minecraft.text.Text;
import net.minecraft.util.Identifier;
import net.minecraft.world.gen.feature.ConfiguredFeature;
import net.minecraft.world.gen.feature.Feature;
import net.minecraft.world.gen.feature.FeatureConfig;
import net.minecraft.world.gen.feature.util.FeatureContext;

/**
 * The TreeGenerator objects as vanilla worldgen features.
 *
 * <ul>
 *   <li>{@code fantasymapgenerator:treegen_object} -- one preset
 *       ({@link TreeObjectFeature});</li>
 *   <li>{@code fantasymapgenerator:treegen_mix} -- one layer of a biome's mix
 *       ({@link TreeMixFeature}).</li>
 * </ul>
 *
 * <p>The configured and placed features, the structure files and their place in
 * each biome's feature list are all data, generated by {@code tools/fmgtrees/
 * treegen.py} and {@code make_datapack.py}. Worldgen registries load with the
 * world, so a changed feature JSON needs the world reopened; the structure files
 * themselves reload with {@code /reload}.
 *
 * <p>{@code /fmg trees stats} shows, per biome layer, how often a spot was tried,
 * placed or refused and why -- the numbers to look at when a forest comes out
 * thinner than its mix says.
 */
public final class TreeFeatures {

    public static final Feature<TreeObjectConfig> OBJECT = new TreeObjectFeature();
    public static final Feature<TreeMixConfig> MIX = new TreeMixFeature();

    private TreeFeatures() {
    }

    public static void registerFeatures(RegisterEvent event) {
        event.register(RegistryKeys.FEATURE, helper -> {
            helper.register(Identifier.of(FantasyMapGenerator.MOD_ID, "treegen_object"), OBJECT);
            helper.register(Identifier.of(FantasyMapGenerator.MOD_ID, "treegen_mix"), MIX);
        });
    }

    public static void register() {
        // no player = the sync after /reload
        NeoForge.EVENT_BUS.addListener(OnDatapackSyncEvent.class, event -> {
            if (event.getPlayer() == null) {
                TreeShapes.clear();
            }
        });
        NeoForge.EVENT_BUS.addListener(ServerStoppedEvent.class, event -> {
            logStats();
            names = null;
            TreeShapes.clear();
            TreeGround.clear();
            PlacedObjects.clearAll();
        });

        NeoForge.EVENT_BUS.addListener(RegisterCommandsEvent.class, event -> event.getDispatcher().register(
                literal("fmg").then(literal("trees")
                        .requires(src -> src.hasPermissionLevel(2))
                        .then(literal("stats").executes(ctx -> stats(ctx.getSource())))
                        .then(literal("reset").executes(ctx -> {
                            TreePlacer.stats().clear();
                            ctx.getSource().sendFeedback(() -> Text.literal("Tree stats reset."), false);
                            return 1;
                        })))));
    }

    /** Everything the placer needs, for one feature call. */
    static TreePlacer.Ctx ctx(FeatureContext<?> context) {
        SurfaceSet set = null;
        if (context.getGenerator() instanceof ImageMapChunkGenerator fmg) {
            String palettes = MapImageCache.get(fmg.mapInfo()).profile().surfacePalettes;
            if (palettes != null) {
                set = SurfaceSet.get(palettes, FMLPaths.CONFIGDIR.get());
            }
        }
        TreeGround ground = new TreeGround(set, context.getWorld().getBottomY());
        return new TreePlacer.Ctx(context.getWorld(), ground, context.getGenerator().getSeaLevel(),
                context.getRandom());
    }

    static byte layer(String name) {
        return switch (name) {
            case "dead" -> PlacedObjects.DEAD;
            case "logs" -> PlacedObjects.LOG;
            case "shrubs" -> PlacedObjects.SHRUB;
            default -> PlacedObjects.TREE;
        };
    }

    private static volatile Map<FeatureConfig, String> names;

    /**
     * {@code oak_woodland/trees} for the mix registered as
     * {@code fantasymapgenerator:treegen/oak_woodland/trees}. Found by config, not
     * through {@code FeatureContext.getFeature()}: a feature placed by a placed
     * feature gets an empty one there.
     */
    static String statsKey(FeatureContext<?> context) {
        Map<FeatureConfig, String> map = names;
        if (map == null) {
            map = new IdentityHashMap<>();
            for (Map.Entry<RegistryKey<ConfiguredFeature<?, ?>>, ConfiguredFeature<?, ?>> e : context.getWorld()
                    .getRegistryManager().get(RegistryKeys.CONFIGURED_FEATURE).getEntrySet()) {
                if (e.getValue().config() instanceof TreeMixConfig) {
                    String p = e.getKey().getValue().getPath();
                    map.put(e.getValue().config(), p.startsWith("treegen/") ? p.substring(8) : p);
                }
            }
            names = map;
        }
        return map.getOrDefault(context.getConfig(), "?");
    }

    private static List<String> statLines() {
        List<String> lines = new ArrayList<>();
        Map<String, LongAdder> stats = TreePlacer.stats();
        List<String> keys = new ArrayList<>(stats.keySet());
        keys.sort(null);
        String current = null;
        StringBuilder line = null;
        for (String k : keys) {
            int sp = k.indexOf(' ');
            String feature = sp < 0 ? k : k.substring(0, sp);
            String what = sp < 0 ? "" : k.substring(sp + 1);
            if (!feature.equals(current)) {
                if (line != null) lines.add(line.toString());
                current = feature;
                line = new StringBuilder(feature).append(':');
            }
            if (what.equals("us")) {
                line.append(" ms=").append(stats.get(k).sum() / 1000);
            } else {
                line.append(' ').append(what.replace("refused ", "-").replace("stepped down", "smaller"))
                        .append('=').append(stats.get(k).sum());
            }
        }
        if (line != null) lines.add(line.toString());
        return lines;
    }

    private static int stats(ServerCommandSource src) {
        List<String> lines = statLines();
        if (lines.isEmpty()) {
            src.sendFeedback(() -> Text.literal("No trees placed yet in this session."), false);
            return 0;
        }
        for (String l : lines) {
            src.sendFeedback(() -> Text.literal(l), false);
        }
        return lines.size();
    }

    private static void logStats() {
        List<String> lines = statLines();
        if (lines.isEmpty()) return;
        FantasyMapGenerator.LOGGER.info("Tree placement this session (tries / placed / refused by reason):");
        for (String l : lines) {
            FantasyMapGenerator.LOGGER.info("  {}", l);
        }
    }
}
