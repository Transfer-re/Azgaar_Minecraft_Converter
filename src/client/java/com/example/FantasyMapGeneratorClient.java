package com.example;

import net.fabricmc.api.ClientModInitializer;
import net.fabricmc.fabric.api.resource.ResourceManagerHelper;
import net.fabricmc.fabric.api.resource.ResourcePackActivationType;
import net.fabricmc.loader.api.FabricLoader;
import net.minecraft.text.Text;
import net.minecraft.util.Identifier;

import com.example.border.ClientBorderOverlay;

public class FantasyMapGeneratorClient implements ClientModInitializer {
	@Override
	public void onInitializeClient() {
		ClientBorderOverlay.registerClient();
		registerConquestSky();
	}

	/**
	 * Conquest Reforged's Polytone sky and fog colormaps target the vanilla
	 * overworld dimension type, which FMG worlds don't use (they have their own
	 * height tiers). This pack, generated by tools/fmgtrees/make_datapack.py,
	 * points FMG's dimension types at the same textures.
	 */
	private static void registerConquestSky() {
		if (!FabricLoader.getInstance().isModLoaded("conquest")) return;
		FabricLoader.getInstance().getModContainer(FantasyMapGenerator.MOD_ID).ifPresent(mod ->
				ResourceManagerHelper.registerBuiltinResourcePack(
						new Identifier(FantasyMapGenerator.MOD_ID, "conquest_sky"), mod,
						Text.literal("Fantasy Map: Conquest sky"), ResourcePackActivationType.ALWAYS_ENABLED));
	}
}
